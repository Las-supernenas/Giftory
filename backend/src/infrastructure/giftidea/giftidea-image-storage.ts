import { randomUUID } from 'node:crypto';
import { mkdir, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { ValidationError } from '../../domain/errors/ValidationError';

export const giftIdeaImagesDirectory = path.resolve(
  process.cwd(),
  'uploads',
  'giftideas',
);

const maxImageSize = 5 * 1024 * 1024;

function imageExtension(buffer: Buffer, mimeType: string): string | null {
  if (
    mimeType === 'image/jpeg' &&
    buffer.length >= 3 &&
    buffer[0] === 0xff &&
    buffer[1] === 0xd8 &&
    buffer[2] === 0xff
  ) {
    return 'jpg';
  }

  if (
    mimeType === 'image/png' &&
    buffer.length >= 8 &&
    buffer.subarray(0, 8).equals(Buffer.from('89504e470d0a1a0a', 'hex'))
  ) {
    return 'png';
  }

  if (
    mimeType === 'image/webp' &&
    buffer.length >= 12 &&
    buffer.toString('ascii', 0, 4) === 'RIFF' &&
    buffer.toString('ascii', 8, 12) === 'WEBP'
  ) {
    return 'webp';
  }

  return null;
}

export async function saveGiftIdeaImage(
  buffer: Buffer,
  mimeType: string,
): Promise<string> {
  const extension = imageExtension(buffer, mimeType);
  if (!extension || buffer.length > maxImageSize) {
    throw new ValidationError('La imagen debe ser JPG, PNG o WebP y pesar como máximo 5 MB.');
  }

  const filename = `${randomUUID()}.${extension}`;
  await mkdir(giftIdeaImagesDirectory, { recursive: true });
  await writeFile(path.join(giftIdeaImagesDirectory, filename), buffer, { flag: 'wx' });
  return filename;
}

export async function deleteGiftIdeaImage(filename: string | null): Promise<void> {
  if (!filename) return;

  // Filenames are generated by this server. Never use a request-supplied path.
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp)$/.test(filename)) {
    return;
  }

  try {
    await unlink(path.join(giftIdeaImagesDirectory, filename));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
}
